from collections.abc import Sequence
from pathlib import Path
from typing import TYPE_CHECKING, Any, Protocol

from .options import Backdrop, Theme, WindowPlatform

if TYPE_CHECKING:
    from .dialogs import FileType, MessageBox
    from .drag_out import DragOut
    from .regions import TitleBarRegions


class ContentBackend(Protocol):
    def load_url(self, url: str) -> None: ...

    def load_html(self, html: str) -> None: ...

    def emit(self, event: str, payload: Any) -> None: ...


class WindowBackend(ContentBackend, Protocol):
    platform: WindowPlatform
    # Whether the backend can make the page's title bar the window's
    supports_custom_chrome: bool

    @property
    def native_window(self) -> Any:
        """Either a NSWindow, a WinForms Form or a Gtk.Window"""
        ...

    def open(self) -> None: ...

    def show(self) -> None: ...

    def hide(self) -> None: ...

    def close(self) -> None: ...

    def set_title(self, title: str) -> None: ...

    def frame(self) -> tuple[int, int, int, int]: ...

    def minimize(self) -> None: ...

    def toggle_maximize(self) -> None: ...

    def toggle_fullscreen(self) -> None: ...

    # Make the window look like a theme says (it's in the owner's theme already), from any thread
    def set_theme(self, theme: Theme) -> None: ...

    def set_backdrop(self, backdrop: Backdrop) -> None: ...

    def backdrops(self) -> tuple[Backdrop, ...]: ...

    # Where the page drew its title bar (None: it has none), from any thread
    def set_title_bar_regions(self, regions: "TitleBarRegions | None") -> None: ...

    # The page has drawn its first frame and reported its title bar
    def page_ready(self) -> None: ...

    def chrome_details(self) -> dict[str, Any]: ...

    def file_dialog(self, file_types: Sequence["FileType"], *, save: bool = False, multiple: bool = False,
                    name: str = "", directory: Path | None = None, folder: bool = False) -> list[Path] | None: ...

    def message_box(self, box: "MessageBox") -> int: ...

    def set_edited(self, edited: bool) -> None: ...

    def show_devtools(self) -> None: ...

    # The names of the files dragged over the window
    def dragged_names(self) -> list[str] | None: ...

    # Starts a system drag of what the page drags, from any thread. Whether it began
    def begin_drag_out(self, drag: "DragOut") -> bool: ...
